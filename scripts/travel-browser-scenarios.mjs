export async function travelSupportAudit(page){
 const assert=(condition,message)=>{if(!condition)throw Error(message)}
 const errors=[];page.on('pageerror',error=>errors.push(error.message))
 await page.setViewportSize({width:1440,height:1000})
 await page.goto('http://127.0.0.1:5173/?day=2')
 await page.evaluate(()=>localStorage.removeItem('tokyo-2026-visits-v1'))
 await page.reload()
 await page.locator('.today-focus > summary').click()
 assert((await page.locator('.protected-time').innerText()).includes('11:00–12:00'),'Ticket window missing')
 await page.getByRole('button',{name:'지연·피로 시',exact:true}).click()
 assert((await page.locator('.today-focus').innerText()).includes('포레스트 입장을 먼저'),'Delay guidance missing')
 await page.getByLabel('다음 일정 길찾기 출발지').selectOption('lodging')
 const direction=await page.locator('.today-focus a[href*="maps/dir"]').getAttribute('href')
 assert(new URL(direction).searchParams.get('origin').includes('新橋5丁目29'),'Selected origin not applied')
 await page.locator('.visit-control select').nth(0).selectOption('done')
 await page.locator('.visit-control select').nth(1).selectOption('skipped')
 assert((await page.locator('.today-focus > summary').innerText()).includes('10:30'),'Next itinerary ignores progress')
 await page.reload()
 assert(await page.locator('.visit-control select').nth(0).inputValue()==='done','Visit state did not persist')
 assert(await page.locator('.visit-control select').nth(1).inputValue()==='skipped','Skipped state did not persist')
 await page.locator('.today-focus > summary').click()
 await page.locator('.today-focus .nearby-options summary').click()
 assert(await page.locator('.today-focus .nearby-options a').count()===3,'Nearby alternatives missing')
 const layouts=[]
 for(const width of [1440,768,390,320]){
  await page.setViewportSize({width,height:900})
  assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'Travel support overflow '+width)
  await page.getByRole('button',{name:'필수 정보',exact:true}).click()
  const dialog=page.locator('.essentials-dialog');await dialog.waitFor()
  assert((await dialog.innerText()).includes('10:00 입장'),'Harry fixed entry missing')
  const box=await dialog.boundingBox();assert(box.x>=0&&box.x+box.width<=width,'Essential dialog outside viewport')
  if(width===390)await page.screenshot({path:'output/playwright/travel-essentials-mobile.png'})
  await page.keyboard.press('Escape')
  layouts.push({width,overflow:false,essentials:'passed'})
 }
 await page.setViewportSize({width:390,height:844})
 await page.locator('.itinerary-scroll').evaluate(el=>el.scrollTo(0,0))
 await page.screenshot({path:'output/playwright/travel-support-mobile.png'})
 await page.getByRole('button',{name:'테마 탐색',exact:true}).click();await page.locator('.theme-intro').waitFor()
 await page.getByRole('button',{name:/도쿄타워를 담는 곳/}).first().click()
 await page.locator('[data-spot="akabanebashi-photo"] .theme-card-detail-open').click()
 await page.locator('[data-spot="akabanebashi-photo"] .theme-verification > summary').click()
 await page.locator('[data-spot="akabanebashi-photo"] .official-evidence').waitFor()
 assert(await page.locator('.official-evidence').count()===1,'Individual theme evidence missing')
 await page.locator('[data-spot="akabanebashi-photo"] .official-evidence details summary').click()
 assert((await page.locator('[data-spot="akabanebashi-photo"] .official-evidence').innerText()).includes('특정 촬영'),'Photo scope missing')
 await page.screenshot({path:'output/playwright/theme-official-evidence-mobile.png'})
 await page.keyboard.press('Escape')
 await page.getByRole('button',{name:/책방·음악·산책/}).click()
 assert((await page.locator('[data-spot="kioi-seido"] .theme-card-note').innerText()).includes('일반 공개를 하지 않는'),'Closed facility was presented as available')
 assert(!errors.length,'Travel support browser exceptions')
 await page.evaluate(()=>localStorage.removeItem('tokyo-2026-visits-v1'))
 return {ticketWindow:'11:00–12:00',pass:'Trainer’s Pass',progressReload:'passed',delayGuidance:'passed',nearbyLinks:3,individualEvidence:'passed',layouts,pageErrors:errors}
}
