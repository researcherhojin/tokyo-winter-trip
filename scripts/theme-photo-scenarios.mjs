export async function themePhotoAudit(page){
 const assert=(condition,message)=>{if(!condition)throw Error(message)}
 const errors=[];page.on('pageerror',error=>errors.push(error.message))
 await page.setViewportSize({width:1440,height:1000})
 await page.goto('http://127.0.0.1:5173/?day=1&view=themes')
 const response=await page.request.get('http://127.0.0.1:5173/api/catalog/themes')
 const {data}=await response.json()
 const covers=[]
 const coverage=[]
 const collator=new Intl.Collator('ko',{numeric:true,sensitivity:'base'})
 for(const theme of data.themes){
  await page.getByRole('navigation',{name:'여행 테마'}).getByRole('button',{name:new RegExp(theme.title.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'))}).click()
  const cover=page.locator('.theme-cover .theme-image')
  if(theme.coverPhotoId){
   await cover.waitFor()
   const image=cover.locator('.photo-main');await image.evaluate(img=>{img.loading='eager';return img.decode()})
   assert(await cover.getAttribute('data-photo-id')===theme.coverPhotoId,'Wrong theme cover '+theme.id)
   assert(await image.evaluate(img=>img.naturalWidth>0),'Cover failed '+theme.id)
   covers.push({theme:theme.id,photo:theme.coverPhotoId,decoded:true})
  }else assert(await cover.count()===0,'Unverified cover should not be substituted '+theme.id)
  const photos=page.locator('.theme-spot .theme-image img')
  for(const photo of await photos.all())await photo.evaluate(img=>{img.loading='eager';return img.decode()})
  const withPhoto=await page.locator('.theme-spot.has-photo').count()
  const withoutPhoto=await page.locator('.theme-spot.without-photo').count()
  assert(withPhoto+withoutPhoto===theme.spots.length,'Candidate hidden '+theme.id)
  const names=await page.locator('.theme-spot h3').allTextContents()
  assert(JSON.stringify(names)===JSON.stringify([...names].sort(collator.compare)),'Name order inconsistent '+theme.id)
  assert(await page.locator('.theme-visit-info').count()===theme.spots.length,'Hours missing '+theme.id)
  const productIds=new Set(theme.spots.filter(spot=>spot.kind==='product').map(spot=>spot.id))
  for(const card of await page.locator('.theme-spot').all()){const fields=await card.locator('.theme-visit-info dt').allTextContents().then(values=>values.join(','));assert(fields===(productIds.has(await card.getAttribute('data-spot'))?'제조·판매,구매 전':'운영시간,휴무'),'Uneven card fields '+theme.id)}
  coverage.push({theme:theme.id,total:theme.spots.length,withPhoto,withoutPhoto})
  const heights=await page.locator('.theme-spot').evaluateAll(cards=>cards.map(card=>Math.round(card.getBoundingClientRect().height)))
  assert(Math.max(...heights)<800,'Default cards are too tall '+theme.id)
  coverage[coverage.length-1].maxCardHeight=Math.max(...heights)
  if(theme.id==='night-view'){
   assert(withPhoto===12&&withoutPhoto===0,'Every night destination needs an actual night photo')
   for(const figure of await page.locator('.theme-spot .theme-image').all())assert(['night','blue-hour'].includes(await figure.getAttribute('data-time-of-day')),'Day photo leaked into night theme')
   await page.setViewportSize({width:2560,height:1400});
   const columns=await page.locator('.theme-spots').first().evaluate(element=>getComputedStyle(element).gridTemplateColumns.split(' ').length)
   assert(columns<=4,'Wide layout has too many columns')
   await page.screenshot({path:'output/playwright/night-photos-wide.png'})
   await page.setViewportSize({width:390,height:844});
   await page.screenshot({path:'output/playwright/night-photos-mobile.png'})
   await page.setViewportSize({width:1440,height:1000})
  }
 }
 await page.getByRole('navigation',{name:'여행 테마'}).getByRole('button',{name:/도쿄타워를 담는 곳/}).click()
 await page.getByLabel('장소 정렬').selectOption('photo')
 const photoOrder=await page.locator('.theme-spot').evaluateAll(cards=>cards.map(card=>card.classList.contains('has-photo')))
 const photoCount=data.themes.find(theme=>theme.id==='tower-photos').spots.filter(spot=>spot.photoId).length
 assert(photoOrder.slice(0,photoCount).every(Boolean)&&photoOrder.slice(photoCount).every(value=>!value),'Photo-first order failed')
 await page.getByLabel('장소 정렬').selectOption('name')
 const first=page.locator('[data-spot="akabanebashi-photo"] .theme-image')
 const second=page.locator('[data-spot="azabudai-photo"] .theme-image')
 assert(await first.getAttribute('data-photo-id')==='views-akabanebashi','Station view missing')
 assert(await second.locator('[data-photo-id="views-azabudai"]').count()===1,'Identified view missing from the gallery')
 const shiba=page.locator('[data-spot="shiba-seven-photo"]')
 assert(await shiba.evaluate(el=>el.classList.contains('without-photo')&&el.classList.contains('has-reference')),'Shiba stand-in counted as exact')
 assert(await shiba.locator('.theme-image').getAttribute('data-photo-id')==='reference-shiba-seven','Rejected Shiba photo was restored')
 assert(await page.locator('[data-spot="hamamatsu-deck-photo"] .theme-image').getAttribute('data-photo-id')==='more-hamamatsu-deck-photo-3'&&await page.locator('[data-spot="hamamatsu-deck-photo"] [data-photo-id="audit-takeshiba-deck-night"]').count()===1,'Takeshiba deck photos missing')
 const frames=[]
 const ratio=box=>box.width/box.height
 for(const width of [1440,768,390,320]){
  await page.setViewportSize({width,height:1000})
  assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'Photo overflow '+width)
  for(const figure of [first,second]){
   const frame=await figure.locator('.theme-gallery-frame').boundingBox()
   assert(Math.abs(ratio(frame)-4/3)<.02,'Card photo frame should be 4:3 '+width)
   const slide=figure.locator('.photo-slide').first()
   assert(await slide.getAttribute('data-photo-mode')==='whole','Whole view expected '+width)
   const main=slide.locator('.photo-main');await main.evaluate(img=>{img.loading='eager';return img.decode()})
   const shown=await main.evaluate(img=>{const box=img.getBoundingClientRect();const scale=Math.min(box.width/img.naturalWidth,box.height/img.naturalHeight);return {fit:getComputedStyle(img).objectFit,w:img.naturalWidth*scale,h:img.naturalHeight*scale,bw:box.width,bh:box.height}})
   assert(shown.fit==='contain'&&shown.w<=shown.bw+1&&shown.h<=shown.bh+1,'Portrait view must be fully visible at rest '+width)
  }
  frames.push({width,ratio:'4:3',portraitVisibleAtRest:'100%',overflow:false})
 }
 await page.setViewportSize({width:1440,height:1000})
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.screenshot({path:'output/playwright/theme-view-photos-desktop.png'})
 const coverBox=await page.locator('.theme-cover .theme-gallery-frame').boundingBox();assert(Math.abs(ratio(coverBox)-1.5)<.03&&coverBox.height<=160,'Cover frame should stay a small 3:2 thumbnail')
 const opener=second.locator('.theme-image-open').first()
 await opener.scrollIntoViewIfNeeded()
 const enterOpacity=await opener.evaluate(async el=>{el.click();await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));return +getComputedStyle(document.querySelector('.theme-photo-dialog')).opacity})
 const dialog=page.locator('.theme-photo-dialog');await dialog.waitFor();await page.waitForTimeout(320)
 assert(enterOpacity<1&&+await dialog.evaluate(el=>getComputedStyle(el).opacity)===1,'Dialog should fade in')
 assert(await dialog.locator('img').evaluate(img=>getComputedStyle(img).objectFit)==='contain','Enlarged portrait cropped')
 assert((await dialog.innerText()).includes('아자부다이'),'Expanded photo must retain the actual place caption')
 await page.screenshot({path:'output/playwright/theme-photo-enlarged.png'})
 await page.keyboard.press('Escape')
 assert(await dialog.evaluate(el=>el.classList.contains('is-closing')),'Dialog should play an exit transition')
 await page.waitForTimeout(300);assert(await dialog.count()===0,'Photo dialog did not close')
 assert(await opener.evaluate(el=>document.activeElement===el),'Focus did not return to the photo')
 await page.getByRole('navigation',{name:'여행 테마'}).getByRole('button',{name:/캐릭터·굿즈/}).click()
 const mega=page.locator('[data-spot="subculture-mega"] .theme-gallery')
 await mega.scrollIntoViewIfNeeded()
 const megaSlide=mega.locator('.photo-slide').first()
 const image=megaSlide.locator('.photo-main'),button=megaSlide.locator('.theme-image-open')
 await image.evaluate(img=>{img.loading='eager';return img.decode()})
 const uncropped=()=>page.locator('.theme-spot .photo-slide.is-loaded .photo-main').evaluateAll(images=>images.filter(img=>img.getBoundingClientRect().width>0).every(img=>{const box=img.getBoundingClientRect();const fit=getComputedStyle(img).objectFit;const scale=new DOMMatrixReadOnly(getComputedStyle(img).transform==='none'?undefined:getComputedStyle(img).transform).a;return fit==='contain'&&scale===1}))
 assert(await uncropped(),'A card photo is cropped at rest')
 await page.mouse.move(0,0);await page.waitForTimeout(400)
 const dim=()=>button.evaluate(el=>+getComputedStyle(el,'::before').opacity)
 const frameBefore=await button.boundingBox()
 const base=await dim()
 await button.hover();await page.waitForTimeout(110)
 const middle=await dim()
 await page.waitForTimeout(380)
 const full=await dim()
 assert(base===0&&middle>0&&middle<full&&Math.abs(full-.22)<.01,'Hover should fade the backdrop through an intermediate frame')
 assert(await uncropped(),'Hover cropped a card photo')
 await page.mouse.move(0,0);await page.waitForTimeout(60)
 const reversing=await dim()
 assert(reversing<full&&reversing>0,'Leaving mid-hover should reverse without snapping')
 await page.waitForTimeout(450)
 assert(await dim()===0,'Hover did not settle')
 const frameAfter=await button.boundingBox()
 assert(Math.abs(frameAfter.height-frameBefore.height)<1&&Math.abs(frameAfter.width-frameBefore.width)<1,'Photo motion changed card layout')
 const dots=mega.locator('.gallery-dots span')
 assert(await dots.count()>=2&&await dots.count()===await mega.locator('.photo-slide').count(),'Gallery dots missing')
 await mega.locator('.theme-gallery-frame').hover();await mega.locator('.gallery-next').click();await page.waitForTimeout(700)
 assert(await dots.nth(1).getAttribute('class')==='active','Next photo not shown')
 await mega.locator('.gallery-prev').focus();await page.keyboard.press('ArrowLeft');await page.waitForTimeout(700)
 assert(await dots.nth(0).getAttribute('class')==='active','Keyboard previous photo failed')
 const reference=page.locator('[data-spot="subculture-chiikawa-tokyo"]')
 await reference.scrollIntoViewIfNeeded()
 assert(await reference.locator('.photo-reference-badge').isVisible(),'Reference badge hidden')
 assert(!await reference.locator('.theme-gallery > .photo-reference-note').count(),'Reference note line should stay out of the card')
 await reference.locator('.theme-image-open').first().click()
 assert((await page.locator('.theme-photo-dialog .photo-reference-note').innerText()).length>15,'Reference difference hidden in the photo view')
 await page.keyboard.press('Escape')
 assert(await reference.evaluate(el=>el.classList.contains('without-photo')&&el.classList.contains('has-reference')),'Reference counted as an exact photo')
 await page.emulateMedia({reducedMotion:'reduce'})
 assert(await image.evaluate(img=>getComputedStyle(img).transitionDuration.split(',').every(value=>value.trim()==='0s')),'Reduced motion setting ignored')
 assert(await button.evaluate(el=>getComputedStyle(el,'::before').transitionDuration)==='0s','Reduced motion hover fade ignored')
 await page.emulateMedia({reducedMotion:'no-preference'})
 await page.setViewportSize({width:390,height:844})
 await mega.scrollIntoViewIfNeeded()
 await page.screenshot({path:'output/playwright/theme-view-photos-mobile.png'})
 const itineraryGuides=[]
 for(const day of [1,2,3,4,5]){
  await page.goto('http://127.0.0.1:5173/?day='+day)
  await page.locator('.stop-overview').first().waitFor()
  const details=page.locator('.stop-details').first()
  await details.locator('summary').click()
  assert(await details.locator('.stop-guide li').count()>=4,'Missing actionable guide '+day)
  assert(await details.locator('.stop-guide-sources a').count()>0,'Missing guide sources '+day)
  assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'Guide overflow '+day)
  itineraryGuides.push({day,guides:await page.locator('.stop-overview').count(),opened:true})
 }
 await page.screenshot({path:'output/playwright/itinerary-guide-mobile.png'})
 assert(!errors.length,'Photo page exceptions: '+errors.join('; '))
 return {covers,coverage,identifiedViews:3,frames,motion:{crop:'none at rest or hover',hoverBackdropOpacity:.22,durationMs:320,intermediateFrame:'passed',uncropped:'passed',reversal:'passed',layoutStable:'passed',carousel:'passed',referenceBadge:'passed',dialogEnterExit:'passed',focusReturn:'passed',reducedMotion:'passed'},enlargement:'passed',itineraryGuides,pageErrors:errors}
}
